function idx = axisNameContains(axisNames, keyword)
% axisNameContains
% Returns logical index of axis names containing the keyword.
%
% INPUT
%   axisNames : cell array of strings
%   keyword   : string or char
%
% OUTPUT
%   idx       : logical index vector

