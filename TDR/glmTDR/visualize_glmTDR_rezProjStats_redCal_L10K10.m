%% ========================================================================
% GLM-TDR across-session slope analysis
%
% This version uses clearer naming:
%   onGoAxes    = rows/axes whose names are Go-related
%   onNoGoAxes  = rows/axes whose names are NoGo-related
%
% Important:
%   The projection already happened upstream when rezProjStats was computed.
%   Here we are plotting slope matrices and selecting rows/axes.
%
% Included statistics:
%   1) muNoGo slopes
%   2) muGo slopes
%   3) diff slopes
%
% diff convention:
%   Stored diff = muGo - muNoGo
%
% For Go axes:
%   signed diff is kept as Go - NoGo
%
% For NoGo axes:
%   signed diff is sign-flipped to NoGo - Go
%
% This makes positive signed diff consistently mean:
%   condition-preferred separation increases with learning.
%% ========================================================================

%% =========================
% Setup: load rezProjStats
