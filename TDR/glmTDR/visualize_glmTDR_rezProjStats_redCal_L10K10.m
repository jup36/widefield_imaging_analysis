% --- Slope, standardized effect size
muGo_slopeC = cellfun(@(a) a.stats.slope.muGo.statSD, ...
    rezProjStats.perMouse(:,1), 'UniformOutput', false);

muGo_slopeSigC = cellfun(@(a) round(a.stats.slope.muGo.p1_cluster, 2) <= 0.051, ...
    rezProjStats.perMouse(:,1), 'UniformOutput', false);

muNoGo_slopeC = cellfun(@(a) a.stats.slope.muNoGo.statSD, ...
    rezProjStats.perMouse(:,1), 'UniformOutput', false);

muNoGo_slopeSigC = cellfun(@(a) round(a.stats.slope.muNoGo.p1_cluster, 2) <= 0.051, ...
    rezProjStats.perMouse(:,1), 'UniformOutput', false);

% --- diff slope
% Stored convention:
%   diff = muGo - muNoGo
